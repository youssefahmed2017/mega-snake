"""Write version_info.txt, the Windows version resource for PyInstaller's --version-file.

    python tools/make_version_file.py    # -> version_info.txt, then pass --version-file version_info.txt

Without it the .exe has no metadata: Task Manager, the file's Properties > Details tab,
SmartScreen and Windows Defender all show a bare "MegaSnake.exe" with no name, publisher
or version. The version comes from GAME_VERSION in constants.py, read as text so this
doesn't import the game (and pygame) at build time. Windows only; other platforms ignore it.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

TEMPLATE = """# UTF-8 - generated by tools/make_version_file.py, do not edit
VSVersionInfo(
  ffi=FixedFileInfo(filevers={tup}, prodvers={tup}, mask=0x3f, flags=0x0, OS=0x40004,
                    fileType=0x1, subtype=0x0, date=(0, 0)),
  kids=[
    StringFileInfo([StringTable('040904B0', [
      StringStruct('CompanyName', 'Youssef Ahmed'),
      StringStruct('FileDescription', 'MEGA SNAKE'),
      StringStruct('FileVersion', '{ver}'),
      StringStruct('InternalName', 'MegaSnake'),
      StringStruct('LegalCopyright', 'Copyright (C) 2026 Youssef Ahmed. GPL-3.0-only.'),
      StringStruct('OriginalFilename', 'MegaSnake.exe'),
      StringStruct('ProductName', 'MEGA SNAKE'),
      StringStruct('ProductVersion', '{ver}'),
      StringStruct('Comments', 'Snake, but with way too many features.')])]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""


def main() -> None:
    match = re.search(r'^GAME_VERSION = "(\d+)\.(\d+)\.(\d+)"', (ROOT / "constants.py").read_text(), re.M)
    if not match:
        raise SystemExit("couldn't find GAME_VERSION = \"X.Y.Z\" in constants.py")
    ver = ".".join(match.groups())
    tup = tuple(int(n) for n in match.groups()) + (0,)
    (ROOT / "version_info.txt").write_text(TEMPLATE.format(ver=ver, tup=tup), encoding="utf-8")
    print(f"wrote version_info.txt for v{ver}")


if __name__ == "__main__":
    main()
